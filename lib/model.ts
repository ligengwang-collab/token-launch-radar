// Token Radar model, version radar-2: one snapshot of the protocol universe in,
// one ranked board out.
//
// The board ranks every pre-token protocol the snapshot records (the watchlist
// first, then every rankable protocol below the floor), by an implied value the
// model derives from the snapshot's own figures only:
//
//   multiple   the market's own price for a TVL dollar in this category: the
//              median market-cap-per-TVL of the live protocols in the same
//              category, shrunk toward the global median where the category
//              has few live comps, clamped to [0.03, 1.50]
//   base       = tvl_usd x multiple
//   growth     = clamp(change_7d, -50, 100) per cent
//   growthMult = 1 + (growth / 100) x 0.40
//   maturity   = 0.70 + min(age_days, 1460) / 1460 x 0.30   (age unknown: 365)
//   implied    = max(1, round(base x growthMult x maturity))
//
// No protocol name is ever special-cased: the same function scores every row.
// Live-token protocols are kept apart and shown at the market's own value,
// never mixed into the ranked board.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's tunable knobs, as the dashboard states them. */
export interface ModelConstants {
  prior_weight: number;
  multiple_floor: number;
  multiple_cap: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
}

export const MODEL: ModelConstants = {
  prior_weight: 4,
  multiple_floor: 0.03,
  multiple_cap: 1.5,
  growth_weight: 0.4,
  growth_floor: -50,
  growth_cap: 100,
  maturity_floor: 0.7,
  maturity_range: 0.3,
  maturity_days: 1460,
  unknown_age_days: 365,
};

